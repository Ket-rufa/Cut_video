func (d *DouyinDownloader) Supports(rawURL string) bool {
	u, err := ValidateDouyinURL(rawURL)
	if err != nil {
		return false
	}
	host := strings.ToLower(u.Hostname())
	return strings.Contains(host, "douyin.com") || strings.Contains(host, "iesdouyin.com")
}

var douyinIDRegex = regexp.MustCompile(`(?:\/video\/|\/note\/|\/share\/video\/|modal_id=)(\d{15,25})`)

// CanonicalURL resolves short links (v.douyin.com) and query modal_id to clean https://www.douyin.com/video/{id}
func (d *DouyinDownloader) CanonicalURL(ctx context.Context, rawURL string) (string, error) {
	u, err := ValidateDouyinURL(rawURL)
	if err != nil {
		return "", err
	}

	host := strings.ToLower(u.Hostname())
	targetURL := rawURL

	// If short URL, resolve redirects with strict hop-by-hop check
	if strings.Contains(host, "v.douyin.com") {
		resolved, err := ResolveRedirectsSafely(ctx, rawURL, allowedDouyinHosts, 5)
		if err != nil {
			return "", fmt.Errorf("resolve Douyin short link: %w", err)
		}
		targetURL = resolved
	}

	// Check if URL contains a modal_id or video ID
	matches := douyinIDRegex.FindStringSubmatch(targetURL)
	if len(matches) >= 2 {
		return fmt.Sprintf("https://www.douyin.com/video/%s", matches[1]), nil
	}

	// Fallback to parsed URL string
	parsed, parseErr := url.Parse(targetURL)
	if parseErr == nil {
		q := parsed.Query()
		if modalID := q.Get("modal_id"); modalID != "" {
			return fmt.Sprintf("https://www.douyin.com/video/%s", modalID), nil
		}
	}

	return targetURL, nil
}

func (d *DouyinDownloader) ensureDouyinCookieFile(cookiePath string) error {
	if fi, err := os.Stat(cookiePath); err == nil && time.Since(fi.ModTime()) < 6*time.Hour && fi.Size() > 20 {
		return nil
	}

	req, err := http.NewRequest(http.MethodGet, "https://live.douyin.com/", nil)
	if err != nil {
		return err
	}
	req.Header.Set("User-Agent", "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36")
	req.Header.Set("Accept", "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8")
	req.Header.Set("Accept-Language", "zh-CN,zh;q=0.9,en;q=0.8")

	resp, err := d.httpClient.Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()

	cookies := resp.Cookies()
	if len(cookies) == 0 {
		return fmt.Errorf("no cookies received from live.douyin.com")
	}

	var sb strings.Builder
	sb.WriteString("# Netscape HTTP Cookie File\n")
	sb.WriteString("# This file was generated by social-video-cutter!\n\n")

	for _, c := range cookies {
		domain := c.Domain
		if domain == "" {
			domain = ".douyin.com"
		} else if !strings.HasPrefix(domain, ".") {
			domain = "." + domain
		}
		path := c.Path
		if path == "" {
			path = "/"
		}
		secure := "FALSE"
		if c.Secure {
			secure = "TRUE"
		}
		expires := time.Now().Add(365 * 24 * time.Hour).Unix()
		if !c.Expires.IsZero() {
			expires = c.Expires.Unix()
		}
		sb.WriteString(fmt.Sprintf("%s\tTRUE\t%s\t%s\t%d\t%s\t%s\n", domain, path, secure, expires, c.Name, c.Value))
	}

	if dir := filepath.Dir(cookiePath); dir != "" {
		_ = os.MkdirAll(dir, 0755)
	}

	return os.WriteFile(cookiePath, []byte(sb.String()), 0644)
}

func findDouyinCookieFile() string {
	cwd, _ := os.Getwd()
	candidates := []string{
		filepath.Join(cwd, "douyin_cookies.txt"),
		filepath.Join(cwd, "douyin cookie", "douyin_cookies.txt"),
		filepath.Join(cwd, "douyin cookie", "www.douyin.com_cookies.txt"),
		filepath.Join(cwd, "www.douyin.com_cookies.txt"),
		filepath.Join(cwd, "cookies_douyin.txt"),
		filepath.Join(cwd, "cookies.txt"),
		filepath.Join(cwd, "..", "douyin_cookies.txt"),
		filepath.Join(cwd, "..", "douyin cookie", "douyin_cookies.txt"),
		filepath.Join(cwd, "..", "douyin cookie", "www.douyin.com_cookies.txt"),
		filepath.Join(cwd, "..", "..", "douyin_cookies.txt"),
		"douyin_cookies.txt",
		"cookies.txt",
		"d:\\CUT_VIDEO_MXH\\douyin_cookies.txt",
		"d:\\CUT_VIDEO_MXH\\douyin cookie\\douyin_cookies.txt",
		"d:\\CUT_VIDEO_MXH\\douyin cookie\\www.douyin.com_cookies.txt",
		"d:\\CUT_VIDEO_MXH\\cookies.txt",
	}
	for _, c := range candidates {
		if fi, err := os.Stat(c); err == nil && !fi.IsDir() && fi.Size() > 20 {
			return c
		}
	}
	return ""
}

// readDouyinCookies reads a Netscape cookie export and returns both the Cookie
// header and the UIFID required by Douyin's current Argus gateway.
func readDouyinCookies(cookiePath string) (string, string, error) {
	f, err := os.Open(cookiePath)
	if err != nil {
		return "", "", err
	}
	defer f.Close()

	now := time.Now().Unix()
	var cookies []string
	var uifid string
	scanner := bufio.NewScanner(f)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.SplitN(line, "\t", 7)
		if len(fields) != 7 || fields[5] == "" {
			continue
		}
		if expires, parseErr := strconv.ParseInt(fields[4], 10, 64); parseErr == nil && expires > 0 && expires < now {
			continue
		}
		cookies = append(cookies, fields[5]+"="+fields[6])
		if strings.EqualFold(fields[5], "UIFID") {
			uifid = fields[6]
		}
	}
	if err := scanner.Err(); err != nil {
		return "", "", err
	}
	if uifid == "" {
		return "", "", fmt.Errorf("cookie file does not contain UIFID")
	}
	return strings.Join(cookies, "; "), uifid, nil
}

func signedDouyinDetailURL(videoID, uifid string, now time.Time) string {
	query := "device_platform=webapp&aid=6383&channel=channel_pc_web&pc_client_type=1" +
		"&version_code=190500&version_name=19.5.0&aweme_id=" + url.QueryEscape(videoID) +
		"&uifid=" + url.QueryEscape(uifid)
	timestamp := now.Unix()
	signedQuery := fmt.Sprintf("%s&timestamp=%d", query, timestamp)
	plain := fmt.Sprintf("%s_%d_A96D855A08C0A9707F8BEF0D9A527E4E_%s", uifid, timestamp, signedQuery)
	signature := fmt.Sprintf("%x", md5.Sum([]byte(plain)))
	return "https://www.douyin.com/aweme/v1/web/aweme/detail/?" + signedQuery +
		"&x-secsdk-web-signature=" + signature
}

func (d *DouyinDownloader) fetchDouyinDetail(ctx context.Context, canonicalURL string) (*douyinAwemeDetail, error) {
	matches := douyinIDRegex.FindStringSubmatch(canonicalURL)
	if len(matches) < 2 {
		return nil, fmt.Errorf("missing Douyin video ID")
	}
	videoID := matches[1]
	cookiePath := findDouyinCookieFile()
	if cookiePath == "" {
		return nil, fmt.Errorf("Douyin cookie file not found")
	}
	cookieHeader, uifid, err := readDouyinCookies(cookiePath)
	if err != nil {
		return nil, fmt.Errorf("read Douyin cookies: %w", err)
	}

	req, err := http.NewRequestWithContext(ctx, http.MethodGet, signedDouyinDetailURL(videoID, uifid, time.Now()), nil)
	if err != nil {
		return nil, err
	}
	req.Header.Set("User-Agent", douyinWebUserAgent)
	req.Header.Set("Accept", "application/json, text/plain, */*")
	req.Header.Set("Referer", canonicalURL+"?previous_page=web_code_link")
	req.Header.Set("Cookie", cookieHeader)
	req.Header.Set("uifid", uifid)

	resp, err := d.httpClient.Do(req)
	if err != nil {
		return nil, fmt.Errorf("request signed Douyin detail: %w", err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		body, _ := io.ReadAll(io.LimitReader(resp.Body, 512))
		return nil, fmt.Errorf("signed Douyin detail returned HTTP %d: %s", resp.StatusCode, strings.TrimSpace(string(body)))
	}

	var payload douyinDetailResponse
	if err := json.NewDecoder(resp.Body).Decode(&payload); err != nil {
		return nil, fmt.Errorf("decode signed Douyin detail: %w", err)
	}
	if payload.AwemeDetail == nil || payload.AwemeDetail.AwemeID != videoID {
		return nil, fmt.Errorf("Douyin detail unavailable (status %d: %s)", payload.StatusCode, payload.StatusMsg)
	}
	return payload.AwemeDetail, nil
}

func firstDouyinURL(resource douyinURLResource) string {
	for _, candidate := range resource.URLList {
		if strings.HasPrefix(candidate, "https://") || strings.HasPrefix(candidate, "http://") {
			return candidate
		}
	}
	return ""
}

type douyinProbeResult struct {
	url     string
	elapsed time.Duration
}

func newDouyinMediaClient(maxConnections int) *http.Client {
	transport := http.DefaultTransport.(*http.Transport).Clone()
	transport.MaxIdleConns = maxConnections * 2
	transport.MaxIdleConnsPerHost = maxConnections
	transport.MaxConnsPerHost = maxConnections
	transport.ResponseHeaderTimeout = 10 * time.Second
	return &http.Client{Transport: transport}
}

func douyinMediaRequest(ctx context.Context, rawURL, byteRange string) (*http.Request, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, rawURL, nil)
	if err != nil {
		return nil, err
	}
	req.Header.Set("User-Agent", douyinWebUserAgent)
	req.Header.Set("Referer", "https://www.douyin.com/")
	if byteRange != "" {
		req.Header.Set("Range", "bytes="+byteRange)
	}
	return req, nil
}

// rankDouyinCDNs measures a small byte range from every mirror. Douyin often
// returns mirrors whose throughput differs by more than an order of magnitude.
func rankDouyinCDNs(ctx context.Context, candidates []string) []string {
	if len(candidates) < 2 {
		return candidates
	}
	probeCtx, cancel := context.WithTimeout(ctx, 5*time.Second)
	defer cancel()
	client := newDouyinMediaClient(len(candidates))
	results := make(chan douyinProbeResult, len(candidates))
	var wg sync.WaitGroup
	for _, candidate := range candidates {
		if !strings.HasPrefix(candidate, "http://") && !strings.HasPrefix(candidate, "https://") {
			continue
		}
		wg.Add(1)
		go func(rawURL string) {
			defer wg.Done()
			started := time.Now()
			req, err := douyinMediaRequest(probeCtx, rawURL, "0-524287")
			if err != nil {
				return
			}
			resp, err := client.Do(req)
			if err != nil {
				return
			}
			defer resp.Body.Close()
			if resp.StatusCode != http.StatusPartialContent {
				return
			}
			if n, copyErr := io.Copy(io.Discard, resp.Body); copyErr == nil && n == 524288 {
				results <- douyinProbeResult{url: rawURL, elapsed: time.Since(started)}
			}
		}(candidate)
	}
	go func() {
		wg.Wait()
		close(results)
	}()

	var ranked []douyinProbeResult
	for result := range results {
		ranked = append(ranked, result)
	}
	sort.Slice(ranked, func(i, j int) bool { return ranked[i].elapsed < ranked[j].elapsed })
	ordered := make([]string, 0, len(candidates))
	seen := make(map[string]bool, len(candidates))
	for _, result := range ranked {
		ordered = append(ordered, result.url)
		seen[result.url] = true
	}
	for _, candidate := range candidates {
		if !seen[candidate] {
			ordered = append(ordered, candidate)
		}
	}
	return ordered
}

type atomicProgressWriter struct {
	w       io.Writer
	written *atomic.Int64
}

func (w atomicProgressWriter) Write(p []byte) (int, error) {
	n, err := w.w.Write(p)
	w.written.Add(int64(n))
	return n, err
}

func downloadDouyinRanges(ctx context.Context, client *http.Client, candidates []string, outputPath string, total int64, progress ProgressCallback) error {
	connections := 8
	if maxUseful := int(total / (4 * 1024 * 1024)); maxUseful < connections {
		connections = maxUseful
	}
	if connections < 2 {
		return fmt.Errorf("media is too small for a ranged download")
	}

	out, err := os.OpenFile(outputPath, os.O_CREATE|os.O_RDWR|os.O_TRUNC, 0644)
	if err != nil {
		return err
	}
	defer out.Close()
	if err := out.Truncate(total); err != nil {
		return err
	}

	downloadCtx, cancel := context.WithCancel(ctx)
	defer cancel()
	var downloaded atomic.Int64
	errCh := make(chan error, connections)
	var wg sync.WaitGroup
	chunkSize := (total + int64(connections) - 1) / int64(connections)
	for part := 0; part < connections; part++ {
		start := int64(part) * chunkSize
		end := start + chunkSize - 1
		if end >= total {
			end = total - 1
		}
		if start > end {
			continue
		}
		wg.Add(1)
		go func(part int, start, end int64) {
			defer wg.Done()
			var lastErr error
			for attempt := 0; attempt < 3; attempt++ {
				rawURL := candidates[attempt%len(candidates)]
				req, reqErr := douyinMediaRequest(downloadCtx, rawURL, fmt.Sprintf("%d-%d", start, end))
				if reqErr != nil {
					lastErr = reqErr
					continue
				}
				resp, reqErr := client.Do(req)
				if reqErr != nil {
					lastErr = reqErr
					continue
				}
				if resp.StatusCode != http.StatusPartialContent {
					lastErr = fmt.Errorf("CDN does not support ranges (HTTP %d)", resp.StatusCode)
					resp.Body.Close()
					continue
				}
				writer := atomicProgressWriter{w: io.NewOffsetWriter(out, start), written: &downloaded}
				copied, copyErr := io.CopyBuffer(writer, resp.Body, make([]byte, 1024*1024))
				resp.Body.Close()
				if copyErr == nil && copied == end-start+1 {
					return
				}
				// A retry overwrites this entire range, so remove bytes counted by the failed attempt.
				downloaded.Add(-copied)
				lastErr = copyErr
				if lastErr == nil {
					lastErr = fmt.Errorf("short ranged response: got %d, want %d", copied, end-start+1)
				}
			}
			errCh <- fmt.Errorf("part %d: %w", part, lastErr)
			cancel()
		}(part, start, end)
	}
	done := make(chan struct{})
	go func() {
		wg.Wait()
		close(done)
	}()

	ticker := time.NewTicker(time.Second)
	defer ticker.Stop()
	lastBytes := int64(0)
	for {
		select {
		case <-done:
			select {
			case downloadErr := <-errCh:
				return downloadErr
			default:
			}
			if downloaded.Load() != total {
				return fmt.Errorf("incomplete ranged download: got %d, want %d", downloaded.Load(), total)
			}
			return out.Sync()
		case <-ticker.C:
			current := downloaded.Load()
			speed := current - lastBytes
			lastBytes = current
			pct := 5 + int(float64(current)/float64(total)*85)
			if pct > 90 {
				pct = 90
			}
			eta := 0
			if speed > 0 {
				eta = int((total - current) / speed)
			}
			progress(DownloadProgress{Status: "DOWNLOADING", Progress: pct, DownloadedBytes: current, TotalBytes: total, Speed: speed, ETA: eta})
		case <-ctx.Done():
			return ctx.Err()
		}
	}
}

func downloadDouyinSingle(ctx context.Context, client *http.Client, streamURL, outputPath string, expectedSize int64, progress ProgressCallback) (int64, error) {
	req, err := douyinMediaRequest(ctx, streamURL, "")
	if err != nil {
		return 0, err
	}
	resp, err := client.Do(req)
	if err != nil {
		return 0, fmt.Errorf("download signed Douyin stream: %w", err)
	}
	defer resp.Body.Close()
	if resp.StatusCode < 200 || resp.StatusCode >= 300 {
		return 0, fmt.Errorf("Douyin media server returned HTTP %d", resp.StatusCode)
	}
	total := resp.ContentLength
	if total <= 0 {
		total = expectedSize
	}
	out, err := os.Create(outputPath)
	if err != nil {
		return 0, fmt.Errorf("create Douyin output: %w", err)
	}
	defer out.Close()
	progress(DownloadProgress{Status: "DOWNLOADING", Progress: 5, TotalBytes: total})

	buffer := make([]byte, 4*1024*1024)
	var downloaded, lastBytes int64
	lastReport := time.Now()
	for {
		n, readErr := resp.Body.Read(buffer)
		if n > 0 {
			if _, writeErr := out.Write(buffer[:n]); writeErr != nil {
				return downloaded, fmt.Errorf("write Douyin output: %w", writeErr)
			}
			downloaded += int64(n)
			if elapsed := time.Since(lastReport); elapsed >= time.Second {
				pct := 50
				if total > 0 {
					pct = 5 + int(float64(downloaded)/float64(total)*85)
					if pct > 90 {
						pct = 90
					}
				}
				speed := int64(float64(downloaded-lastBytes) / elapsed.Seconds())
				eta := 0
				if speed > 0 && total > downloaded {
					eta = int((total - downloaded) / speed)
				}
				progress(DownloadProgress{Status: "DOWNLOADING", Progress: pct, DownloadedBytes: downloaded, TotalBytes: total, Speed: speed, ETA: eta})
				lastBytes = downloaded
				lastReport = time.Now()
			}
		}
		if readErr == io.EOF {
			break
		}
		if readErr != nil {
			return downloaded, fmt.Errorf("read Douyin stream: %w", readErr)
		}
	}
	return downloaded, out.Sync()
}

func selectDouyinStream(detail *douyinAwemeDetail, quality string) (string, douyinURLResource) {
	var selected douyinBitRate
	found := false
	selectedPixels := 0
	for _, rate := range detail.Video.BitRates {
		if rate.IsH265 != 0 || firstDouyinURL(rate.PlayAddr) == "" {
			continue
		}
		pixels := rate.PlayAddr.Width * rate.PlayAddr.Height
		if quality == "720p" {
			resolutionAxis := rate.PlayAddr.Height
			if rate.PlayAddr.Width < rate.PlayAddr.Height {
				resolutionAxis = rate.PlayAddr.Width
			}
			if resolutionAxis > 720 {
				continue
			}
		}
		better := !found || rate.BitRate > selected.BitRate
		if quality == "720p" {
			better = !found || pixels > selectedPixels || (pixels == selectedPixels && rate.BitRate > selected.BitRate)
		}
		if better {
			selected = rate
			selectedPixels = pixels
			found = true
		}
	}
	if found {
		return firstDouyinURL(selected.PlayAddr), selected.PlayAddr
	}
	if streamURL := firstDouyinURL(detail.Video.PlayAddrH264); streamURL != "" {
		return streamURL, detail.Video.PlayAddrH264
	}
	return firstDouyinURL(detail.Video.PlayAddr), detail.Video.PlayAddr
}

func analysisFromDouyinDetail(canonicalURL string, detail *douyinAwemeDetail) *VideoAnalysisResult {
	title := detail.ItemTitle
	if title == "" {
		title = detail.Description
	}
	if title == "" {
		title = fmt.Sprintf("Douyin Video (%s)", detail.AwemeID)
	}
	durationMs := detail.DurationMs
	if durationMs == 0 {
		durationMs = detail.Video.DurationMs
	}
	thumbnail := firstDouyinURL(detail.Video.Cover)
	if thumbnail == "" {
		thumbnail = firstDouyinURL(detail.Video.OriginCover)
	}
	avatar := firstDouyinURL(detail.Author.AvatarThumb)
	_, originalStream := selectDouyinStream(detail, "original")
	if originalStream.Width == 0 || originalStream.Height == 0 {
		originalStream.Width = detail.Video.Width
		originalStream.Height = detail.Video.Height
	}
	_, stream720 := selectDouyinStream(detail, "720p")
	if stream720.Width == 0 || stream720.Height == 0 {
		stream720 = originalStream
	}
	formats := []VideoFormatInfo{{
		FormatID: "best", Container: "mp4", Quality: "original",
		Width: originalStream.Width, Height: originalStream.Height, HasVideo: true, HasAudio: true,
	}}
	formats = append(formats, VideoFormatInfo{
		FormatID: "720p", Container: "mp4", Quality: "720p",
		Width: stream720.Width, Height: stream720.Height, HasVideo: true, HasAudio: true,
	})
	return &VideoAnalysisResult{
		Platform: domain.PlatformDouyin, SourceURL: canonicalURL, VideoID: detail.AwemeID,
		Title: title, Description: detail.Description, Thumbnail: thumbnail,
		Duration: int(durationMs / 1000), DurationMs: durationMs,
		Author: AuthorInfo{Name: detail.Author.Nickname, Avatar: avatar}, Formats: formats,
	}
}

func (d *DouyinDownloader) Analyze(ctx context.Context, rawURL string) (*VideoAnalysisResult, error) {
	canonicalURL, err := d.CanonicalURL(ctx, rawURL)
	if err != nil {
		canonicalURL = rawURL
	}

	if _, err := ValidateDouyinURL(canonicalURL); err != nil {
		return nil, err
	}

	// Douyin added an Argus signature requirement in September 2026. Current
	// yt-dlp releases do not send it, so prefer the signed detail endpoint.
	if detail, detailErr := d.fetchDouyinDetail(ctx, canonicalURL); detailErr == nil {
		return analysisFromDouyinDetail(canonicalURL, detail), nil
	}

	videoID := ""
	matches := douyinIDRegex.FindStringSubmatch(canonicalURL)
	if len(matches) >= 2 {
		videoID = matches[1]
	}

	// Strategy 1: Try yt-dlp with user cookie file or auto-generated session cookies
	cookieToUse := findDouyinCookieFile()
	if cookieToUse == "" {
		tempCookiePath := filepath.Join(os.TempDir(), "douyin_session_cookies.txt")
		_ = d.ensureDouyinCookieFile(tempCookiePath)
		if _, statErr := os.Stat(tempCookiePath); statErr == nil {
			cookieToUse = tempCookiePath
		}
	}

	args := []string{
		"--dump-json",
		"--no-playlist",
		"--skip-download",
		"--no-warnings",
		"--add-header", "Referer:https://www.douyin.com/",
		"--add-header", "User-Agent:Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36",
	}

	if cookieToUse != "" {
		args = append(args, "--cookies", cookieToUse)
	}

	args = append(args, "--", canonicalURL)

	cmd := exec.CommandContext(ctx, d.ytdlpPath, args...)
	out, err := cmd.Output()
	if err == nil {
		var meta ytDlpMetadata
		if jsonErr := json.Unmarshal(out, &meta); jsonErr == nil && meta.ID != "" {
			authorName := meta.Uploader
			if authorName == "" {
				authorName = meta.Channel
			}
			title := meta.Title
			if title == "" {
				title = meta.Description
			}
			if title == "" {
				title = fmt.Sprintf("Douyin Video (%s)", meta.ID)
			}

			w := meta.Width
			h := meta.Height
			if w == 0 || h == 0 {
				w = 1920
				h = 1080
			}

			w720 := 1280
			h720 := 720
			if w < h { // vertical video
				w720 = 720
				h720 = 1280
			}

			formats := []VideoFormatInfo{
				{
					FormatID:  "best",
					Container: "mp4",
					Quality:   "original",
					Width:     w,
					Height:    h,
					HasVideo:  true,
					HasAudio:  true,
				},
				{
					FormatID:  "720p",
					Container: "mp4",
					Quality:   "720p",
					Width:     w720,
					Height:    h720,
					HasVideo:  true,
					HasAudio:  true,
				},
				{
					FormatID:  "bestaudio",
					Container: "m4a",
					Quality:   "audio_only",
					HasVideo:  false,
					HasAudio:  true,
					AudioOnly: true,
				},
			}

			return &VideoAnalysisResult{
				Platform:    domain.PlatformDouyin,
				SourceURL:   canonicalURL,
				VideoID:     meta.ID,
				Title:       title,
				Description: meta.Description,
				Thumbnail:   meta.Thumbnail,
				Duration:    int(meta.Duration),
				DurationMs:  int64(meta.Duration) * 1000,
				Author: AuthorInfo{
					Name: authorName,
				},
				Formats: formats,
			}, nil
		}
	}

	// Inspect yt-dlp error
	var stderrMsg string
	if exitErr, ok := err.(*exec.ExitError); ok {
		stderrMsg = string(exitErr.Stderr)
	}

	if strings.Contains(stderrMsg, "Fresh cookies") || strings.Contains(stderrMsg, "403: Forbidden") {
		return nil, fmt.Errorf("DOUYIN_COOKIE_REQUIRED: Douyin chặn quét tự động (HTTP 403: Cần Cookie phiên làm việc). Vui lòng lưu file cookie vào 'douyin_cookies.txt' tại thư mục dự án hoặc tải video trực tiếp trên trình duyệt rồi dùng tab 'Tải tệp lên'")
	}

	return nil, fmt.Errorf("không thể phân tích video Douyin (id: %s): %s", videoID, canonicalURL)
}

func (d *DouyinDownloader) Download(ctx context.Context, opt DownloadOptions, progress ProgressCallback) (*DownloadResult, error) {
	canonicalURL, err := d.CanonicalURL(ctx, opt.SourceURL)
	if err != nil {
		canonicalURL = opt.SourceURL
	}

	if _, err := ValidateDouyinURL(canonicalURL); err != nil {
		return nil, err
	}

	if err := os.MkdirAll(opt.TempDir, 0755); err != nil {
		return nil, fmt.Errorf("create job temp dir: %w", err)
	}

	progress(DownloadProgress{
		Status:   "ANALYZING",
		Progress: 2,
	})

	if opt.Quality != "audio_only" {
		if result, directErr := d.downloadSignedDouyin(ctx, canonicalURL, opt, progress); directErr == nil {
			return result, nil
		}
	}

	cookiePath := findDouyinCookieFile()
	if cookiePath == "" {
		cookiePath = filepath.Join(opt.TempDir, "douyin_cookies.txt")
		_ = d.ensureDouyinCookieFile(cookiePath)
	}

	outputTemplate := filepath.Join(opt.TempDir, "video.%(ext)s")
	formatSelector := "best[ext=mp4]/best"
	if opt.Quality == "audio_only" {
		formatSelector = "bestaudio/best"
	}

	args := []string{
		"--no-playlist",
		"--newline",
		"--concurrent-fragments", "8",
		"--buffer-size", "16M",
		"--retries", "10",
		"--fragment-retries", "10",
		"--file-access-retries", "5",
		"--no-mtime",
		"--add-header", "Referer:https://www.douyin.com/",
		"--add-header", "User-Agent:Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36",
		"--format", formatSelector,
		"--output", outputTemplate,
	}

	if _, statErr := os.Stat(cookiePath); statErr == nil {
		args = append(args, "--cookies", cookiePath)
	}

	if d.ffmpegPath != "" {
		ffmpegDir := filepath.Dir(d.ffmpegPath)
		args = append(args, "--ffmpeg-location", ffmpegDir)
	}

	args = append(args, "--", canonicalURL)

	cmd := exec.CommandContext(ctx, d.ytdlpPath, args...)
	stdout, err := cmd.StdoutPipe()
	if err != nil {
		return nil, fmt.Errorf("stdout pipe: %w", err)
	}
	stderr, err := cmd.StderrPipe()
	if err != nil {
		return nil, fmt.Errorf("stderr pipe: %w", err)
	}

	if err := cmd.Start(); err != nil {
		return nil, fmt.Errorf("start yt-dlp: %w", err)
	}

	lastProgressPct := 5
	progress(DownloadProgress{
		Status:   "DOWNLOADING",
		Progress: 5,
	})

	scanner := bufio.NewScanner(stdout)
	progressRegex := regexp.MustCompile(`\[download\]\s+([\d\.]+)%\s+of\s+~?([\d\.]+\w+)(?:\s+at\s+([\d\.]+\w+/s))?(?:\s+ETA\s+(\d+:\d+:\d+|\d+:\d+|\d+))?`)

	go func() {
		for scanner.Scan() {
			line := scanner.Text()
			matches := progressRegex.FindStringSubmatch(line)
			if len(matches) >= 3 {
				if pctFloat, parseErr := strconv.ParseFloat(matches[1], 64); parseErr == nil {
					scaled := 5 + int(pctFloat*0.85)
					if scaled > lastProgressPct && scaled <= 90 {
						lastProgressPct = scaled
					}

					totalBytes := parseBytesString(matches[2])
					downloadedBytes := int64(float64(totalBytes) * (pctFloat / 100.0))
					var speed int64
					var eta int
					if len(matches) >= 4 && matches[3] != "" {
						speed = parseSpeedString(matches[3])
					}
					if len(matches) >= 5 && matches[4] != "" {
						eta = parseETAString(matches[4])
					}

					progress(DownloadProgress{
						Status:          "DOWNLOADING",
						Progress:        lastProgressPct,
						DownloadedBytes: downloadedBytes,
						TotalBytes:      totalBytes,
						Speed:           speed,
						ETA:             eta,
					})
				}
			}
		}
	}()

	var errLines []string
	errScanner := bufio.NewScanner(stderr)
	go func() {
		for errScanner.Scan() {
			errLines = append(errLines, errScanner.Text())
		}
	}()

	cmdErr := cmd.Wait()
	if cmdErr != nil {
		errDetail := strings.Join(errLines, "\n")
		if strings.Contains(errDetail, "Fresh cookies") || strings.Contains(errDetail, "403: Forbidden") {
			return nil, fmt.Errorf("DOUYIN_COOKIE_REQUIRED: Douyin chặn tải tự động (HTTP 403: Cần Cookie phiên làm việc). Vui lòng lưu file cookie vào 'douyin_cookies.txt' tại thư mục dự án hoặc tải video trực tiếp trên trình duyệt rồi dùng tab 'Tải tệp lên'")
		}
		return nil, fmt.Errorf("%w: %s", normalizeYtDlpError(cmdErr, []byte(errDetail)), errDetail)
	}

	// Locate downloaded file
	expectedMP4 := filepath.Join(opt.TempDir, "video.mp4")
	if _, err := os.Stat(expectedMP4); os.IsNotExist(err) {
		entries, _ := os.ReadDir(opt.TempDir)
		for _, entry := range entries {
			if !entry.IsDir() && (strings.HasSuffix(entry.Name(), ".mp4") || strings.HasSuffix(entry.Name(), ".webm") || strings.HasSuffix(entry.Name(), ".m4a")) {
				expectedMP4 = filepath.Join(opt.TempDir, entry.Name())
				break
			}
		}
	}

	verified, verifyErr := VerifyOutputFile(ctx, d.ffprobePath, expectedMP4, opt.Quality != "audio_only")
	if verifyErr != nil {
		return nil, fmt.Errorf("verify Douyin output: %w", verifyErr)
	}

	progress(DownloadProgress{
		Status:   "SAVING",
		Progress: 96,
	})

	return &DownloadResult{
		FilePath:   expectedMP4,
		FileName:   filepath.Base(expectedMP4),
		FileSize:   verified.FileSize,
		MimeType:   "video/mp4",
		Width:      verified.Width,
		Height:     verified.Height,
		DurationMs: verified.DurationMs,
	}, nil
}

func (d *DouyinDownloader) downloadSignedDouyin(ctx context.Context, canonicalURL string, opt DownloadOptions, progress ProgressCallback) (*DownloadResult, error) {
	detail, err := d.fetchDouyinDetail(ctx, canonicalURL)
	if err != nil {
		return nil, err
	}
	streamURL, stream := selectDouyinStream(detail, strings.ToLower(opt.Quality))
	if streamURL == "" {
		return nil, fmt.Errorf("signed Douyin detail did not contain a playable H.264 stream")
	}
	outputPath := filepath.Join(opt.TempDir, "video.mp4")
	candidates := make([]string, 0, len(stream.URLList))
	for _, candidate := range stream.URLList {
		if strings.HasPrefix(candidate, "https://") || strings.HasPrefix(candidate, "http://") {
			candidates = append(candidates, candidate)
		}
	}
	if len(candidates) == 0 {
		candidates = []string{streamURL}
	}
	candidates = rankDouyinCDNs(ctx, candidates)
	client := newDouyinMediaClient(8)
	total := stream.DataSize
	progress(DownloadProgress{Status: "DOWNLOADING", Progress: 5, TotalBytes: total})

	var downloaded int64
	if total > 8*1024*1024 {
		err = downloadDouyinRanges(ctx, client, candidates, outputPath, total, progress)
		if err == nil {
			downloaded = total
		}
	}
	if downloaded == 0 {
		downloaded, err = downloadDouyinSingle(ctx, client, candidates[0], outputPath, total, progress)
		if err != nil {
			return nil, err
		}
	}

	verified, err := VerifyOutputFile(ctx, d.ffprobePath, outputPath, true)
	if err != nil {
		return nil, fmt.Errorf("verify signed Douyin output: %w", err)
	}
	progress(DownloadProgress{Status: "SAVING", Progress: 96, DownloadedBytes: downloaded, TotalBytes: total})
	return &DownloadResult{
		FilePath: outputPath, FileName: filepath.Base(outputPath), FileSize: verified.FileSize,
		MimeType: "video/mp4", Width: verified.Width, Height: verified.Height, DurationMs: verified.DurationMs,
	}, nil
}
